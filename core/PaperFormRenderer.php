<?php
/**
 * Paper-form rendering helpers — official DOH/PhilHealth layout.
 *
 * Editability is determined ONLY by Permissions + workflow lock.
 * Role instructional placeholders (e.g. "For Records Staff Only") are never shown.
 */

require_once __DIR__ . '/Permissions.php';

class PaperFormRenderer
{
    private static bool $layoutTestMode = false;
    private static bool $newConsultationMode = false;

    /** @var array<string, bool> */
    private static array $loggedFieldKeys = [];

    /** Phrases from the paper form that must not appear as digital placeholders. */
    private const ROLE_INSTRUCTION_PATTERNS = [
        '/^for\s+.+\s+only$/i',
        '/for records staff only/i',
        '/for nurse\s*\/?\s*midwife only/i',
        '/for attending physician only/i',
        '/for doctor only/i',
        '/for (the\s+)?(rhu|chu)(\s*\/\s*rhu)?\s+personnel only/i',
        '/for philhealth personnel only/i',
        '/for it department only/i',
        '/for receptionist only/i',
    ];

    private const AUTO_GENERATED_FIELDS = [
        'patient_id',
        'ekas_transaction_no',
        'ekas_date_generated',
    ];

    public static function setLayoutTestMode(bool $enabled): void
    {
        self::$layoutTestMode = $enabled;
    }

    public static function isLayoutTestMode(): bool
    {
        return self::$layoutTestMode;
    }

    public static function setNewConsultationMode(bool $enabled): void
    {
        self::$newConsultationMode = $enabled;
    }

    public static function isNewConsultationMode(): bool
    {
        return self::$newConsultationMode;
    }

    /**
     * Digital UI placeholders. Role labels are stripped — ownership is via data-field-group.
     */
    public static function placeholderForGroup(string $group, ?string $override = null, bool $autoGenerated = false): string
    {
        if (self::$layoutTestMode) {
            return '';
        }

        // Auto-generated fields stay blank; value comes from the system.
        if ($autoGenerated) {
            return '';
        }

        if ($override === null) {
            return '';
        }

        $override = trim($override);
        if ($override === '' || self::isRoleInstructionText($override)) {
            return '';
        }

        return $override;
    }

    public static function isRoleInstructionText(string $text): bool
    {
        $text = trim($text);
        if ($text === '') {
            return false;
        }

        foreach (self::ROLE_INSTRUCTION_PATTERNS as $pattern) {
            if (preg_match($pattern, $text)) {
                return true;
            }
        }

        return false;
    }

    public static function isAutoGeneratedField(string $name): bool
    {
        return in_array($name, self::AUTO_GENERATED_FIELDS, true);
    }

    private static function phAttr(string $text): string
    {
        if ($text === '' || self::isRoleInstructionText($text)) {
            return '';
        }
        $escaped = htmlspecialchars($text);
        return ' placeholder="' . $escaped . '"';
    }

    private static function profileAttr(string $name, bool $extended): string
    {
        require_once __DIR__ . '/PatientProfile.php';
        if ($extended && PatientProfile::isProfileExtended($name)) {
            $ro = self::$newConsultationMode ? ' data-profile-readonly="1" readonly' : '';
            return ' data-profile-field="' . htmlspecialchars($name) . '" data-profile-extended="1"' . $ro;
        }
        if (!$extended && PatientProfile::isProfileColumn($name)) {
            $ro = ($name === 'patient_id' || self::$newConsultationMode) ? ' data-profile-readonly="1" readonly' : '';
            return ' data-profile-field="' . htmlspecialchars($name) . '" data-profile-extended="0"' . $ro;
        }
        return '';
    }

    public static function isGroupReadonly(string $role, string $group, bool $lockRecords = false): bool
    {
        $role = Permissions::normalizeRole($role);
        $group = Permissions::normalizeGroup($group);

        // Workflow lock only applies to records-owned groups after submit / hard lock
        if ($lockRecords && in_array($group, ['records_enrollment', 'records_consent', 'records_treatment', 'it'], true)) {
            return true;
        }
        return Permissions::isReadonly($role, $group);
    }

    public static function renderPage(string $pageId, string $role, bool $lockRecords = false): string
    {
        $role = Permissions::normalizeRole($role);
        $path = __DIR__ . '/../forms/paper/' . $pageId . '.php';
        if (!file_exists($path)) {
            return '<div class="paper-sheet"><p class="text-danger">Form layout not found.</p></div>';
        }

        Permissions::debugLog(sprintf(
            'renderPage page=%s role=%s lockRecords=%s editableGroups=%s',
            $pageId,
            $role,
            $lockRecords ? '1' : '0',
            implode(',', Permissions::getEditableGroups($role))
        ));

        ob_start();
        include $path;
        return ob_get_clean();
    }

    /**
     * Decide field edit state from role ownership + workflow lock only (never placeholders).
     *
     * @return array{attrs:string,editable:bool,reason:string}
     */
    public static function resolveFieldState(
        string $role,
        string $group,
        bool $lockRecords,
        array $field = []
    ): array {
        $role = Permissions::normalizeRole($role);
        $group = Permissions::normalizeGroup($group);
        $name = (string) ($field['name'] ?? '');

        if (!empty($field['readonly']) || self::isAutoGeneratedField($name)) {
            return [
                'attrs' => 'readonly',
                'editable' => false,
                'reason' => 'system_readonly',
            ];
        }

        // New consultation: lock permanent patient profile; only visit clinical fields editable.
        if (self::$newConsultationMode) {
            if (in_array($group, ['records_enrollment', 'records_consent', 'it'], true)) {
                return [
                    'attrs' => 'readonly disabled',
                    'editable' => false,
                    'reason' => 'profile_readonly',
                ];
            }
            if ($group === 'records_treatment' && in_array($role, [ROLE_RECORDS, ROLE_IT], true)) {
                return [
                    'attrs' => '',
                    'editable' => true,
                    'reason' => 'new_consultation',
                ];
            }
            if ($group === 'doctor' && Permissions::ownsField($role, $group)) {
                return [
                    'attrs' => '',
                    'editable' => true,
                    'reason' => 'new_consultation',
                ];
            }
        }

        if ($lockRecords && in_array($group, ['records_enrollment', 'records_consent', 'records_treatment', 'it'], true)) {
            self::logFieldOnce("{$role}|{$group}|workflow_lock", "FIELD owner={$group} role={$role} editable=0 reason=workflow_lock");
            return [
                'attrs' => 'readonly disabled',
                'editable' => false,
                'reason' => 'workflow_lock',
            ];
        }

        if (Permissions::ownsField($role, $group)) {
            self::logFieldOnce("{$role}|{$group}|role_owner", "FIELD owner={$group} role={$role} editable=1 reason=role_owner");
            return [
                'attrs' => '',
                'editable' => true,
                'reason' => 'role_owner',
            ];
        }

        self::logFieldOnce("{$role}|{$group}|not_owner", "FIELD owner={$group} role={$role} editable=0 reason=not_owner");
        return [
            'attrs' => 'readonly disabled',
            'editable' => false,
            'reason' => 'not_owner',
        ];
    }

    private static function logFieldOnce(string $key, string $message): void
    {
        if (isset(self::$loggedFieldKeys[$key])) {
            return;
        }
        self::$loggedFieldKeys[$key] = true;
        Permissions::debugLog($message);
    }

    /**
     * Field enable/disable from role ownership + workflow lock only.
     */
    public static function dis(string $role, string $group, bool $lockRecords, array $field = []): string
    {
        return self::resolveFieldState($role, $group, $lockRecords, $field)['attrs'];
    }

    public static function fg(string $group, string $role = '', bool $editable = false, string $reason = ''): string
    {
        $group = Permissions::normalizeGroup($group);
        $attrs = 'data-field-group="' . htmlspecialchars($group) . '" data-field-owner="' . htmlspecialchars($group) . '"';
        if ($role !== '') {
            $attrs .= ' data-perm-role="' . htmlspecialchars(Permissions::normalizeRole($role)) . '"'
                . ' data-perm-editable="' . ($editable ? '1' : '0') . '"'
                . ' data-perm-reason="' . htmlspecialchars($reason) . '"';
        }
        return $attrs;
    }

    public static function name(string $field, bool $extended = false): string
    {
        return $extended ? 'extended[' . htmlspecialchars($field) . ']' : htmlspecialchars($field);
    }

    public static function line(
        string $name,
        string $role,
        string $group,
        bool $lockRecords,
        bool $extended = false,
        string $type = 'text',
        string $extraClass = '',
        ?string $placeholder = null,
        bool $required = false,
        bool $autoGenerated = false
    ): string {
        $isAuto = $autoGenerated || self::isAutoGeneratedField($name);
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name, 'readonly' => $isAuto]);
        $n = self::name($name, $extended);
        $ext = $extended ? ' data-extended="1"' : '';
        $phText = self::placeholderForGroup($group, $placeholder, $isAuto);
        $req = ($required && $state['editable'] && !self::$layoutTestMode) ? ' required' : '';
        return '<input type="' . htmlspecialchars($type) . '" name="' . $n . '" class="pf-line ' . $extraClass . '" '
            . self::fg($group, $role, $state['editable'], $state['reason']) . $ext . self::profileAttr($name, $extended)
            . ' ' . $state['attrs'] . self::phAttr($phText) . $req . '>';
    }

    public static function area(
        string $name,
        string $role,
        string $group,
        bool $lockRecords,
        bool $extended = false,
        int $rows = 3,
        ?string $placeholder = null,
        bool $autoGenerated = false
    ): string {
        $isAuto = $autoGenerated || self::isAutoGeneratedField($name);
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name, 'readonly' => $isAuto]);
        $n = self::name($name, $extended);
        $ext = $extended ? ' data-extended="1"' : '';
        $phText = self::placeholderForGroup($group, $placeholder, $isAuto);
        return '<textarea name="' . $n . '" rows="' . $rows . '" class="pf-area" '
            . self::fg($group, $role, $state['editable'], $state['reason']) . $ext . self::profileAttr($name, $extended)
            . ' ' . $state['attrs'] . self::phAttr($phText) . '></textarea>';
    }

    public static function checkbox(string $name, string $value, string $label, string $role, string $group, bool $lockRecords, bool $extended = false, string $id = ''): string
    {
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name]);
        $n = self::name($name, $extended);
        $ext = $extended ? ' data-extended="1"' : '';
        $id = $id ?: 'cb_' . preg_replace('/[^a-z0-9]/i', '_', $name . '_' . $value);
        return '<label class="pf-check"><input type="checkbox" name="' . $n . '" value="' . htmlspecialchars($value) . '" id="' . htmlspecialchars($id) . '" '
            . self::fg($group, $role, $state['editable'], $state['reason']) . $ext . ' ' . $state['attrs'] . '><span>' . htmlspecialchars($label) . '</span></label>';
    }

    public static function radio(string $name, string $value, string $label, string $role, string $group, bool $lockRecords, bool $extended = false, string $id = ''): string
    {
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name]);
        $n = self::name($name, $extended);
        $ext = $extended ? ' data-extended="1"' : '';
        $id = $id ?: 'rd_' . preg_replace('/[^a-z0-9]/i', '_', $name . '_' . $value);
        return '<label class="pf-radio"><input type="radio" name="' . $n . '" value="' . htmlspecialchars($value) . '" id="' . htmlspecialchars($id) . '" '
            . self::fg($group, $role, $state['editable'], $state['reason']) . $ext . self::profileAttr($name, $extended)
            . ' ' . $state['attrs'] . '><span>' . htmlspecialchars($label) . '</span></label>';
    }

    public static function select(
        string $name,
        array $options,
        string $role,
        string $group,
        bool $lockRecords,
        bool $extended = false,
        ?string $placeholder = null,
        string $extraClass = '',
        bool $required = false
    ): string {
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name]);
        $n = self::name($name, $extended);
        $ext = $extended ? ' data-extended="1"' : '';
        $cls = trim('pf-select ' . $extraClass);
        $req = ($required && $state['editable'] && !self::$layoutTestMode) ? ' required' : '';
        $html = '<select name="' . $n . '" class="' . htmlspecialchars($cls) . '" '
            . self::fg($group, $role, $state['editable'], $state['reason']) . $ext
            . self::profileAttr($name, $extended) . ' ' . $state['attrs'] . $req . '>';
        foreach ($options as $val => $lbl) {
            if ((string) $val === '') {
                $label = $placeholder ?: (string) $lbl;
                $html .= '<option value="">' . htmlspecialchars($label !== '' ? $label : '—') . '</option>';
                continue;
            }
            $html .= '<option value="' . htmlspecialchars((string) $val) . '">' . htmlspecialchars((string) $lbl) . '</option>';
        }
        return $html . '</select>';
    }

    /**
     * Magallanes address control — same layout as original paper fields.
     * Barangay = dropdown; Municipality/Province fixed; composed address in street slot.
     */
    public static function magallanesAddress(
        string $role,
        string $group,
        bool $lockRecords,
        string $layout = 'full'
    ): string {
        require_once __DIR__ . '/MagallanesAddress.php';

        $fixedAttrs = 'readonly data-perm-editable="0" data-perm-reason="system_readonly" data-magallanes-fixed="1"';
        $fixedFg = self::fg($group, $role, false, 'system_readonly');

        $barangaySelect = self::select(
            'address_barangay',
            MagallanesAddress::barangayOptions(),
            $role,
            $group,
            $lockRecords,
            true,
            '—',
            '',
            true
        );

        $municipality = '<input type="text" name="' . self::name('address_municipality', true) . '" class="pf-line" '
            . 'value="' . htmlspecialchars(MagallanesAddress::municipality()) . '" '
            . $fixedFg . ' data-extended="1"' . self::profileAttr('address_municipality', true)
            . ' ' . $fixedAttrs . '>';

        $province = '<input type="text" name="' . self::name('address_province', true) . '" class="pf-line" '
            . 'value="' . htmlspecialchars(MagallanesAddress::province()) . '" '
            . $fixedFg . ' data-extended="1"' . self::profileAttr('address_province', true)
            . ' ' . $fixedAttrs . '>';

        // Same visual as former free-text residential address area
        $composed = '<textarea name="' . self::name('address_street', true) . '" rows="3" class="pf-area" '
            . 'placeholder="" ' . $fixedFg . ' data-extended="1"' . self::profileAttr('address_street', true)
            . ' ' . $fixedAttrs . ' data-magallanes-composed="1"></textarea>';

        if ($layout === 'compact') {
            // ITR: address area only (composed), with barangay choice inside same block
            return '<div class="pf-magallanes-address" data-magallanes-address>'
                . $composed
                . '<div style="margin-top:4px;">' . $barangaySelect . '</div>'
                . '<div style="display:none;">' . $municipality . $province . '</div>'
                . '</div>';
        }

        if ($layout === 'pkrf') {
            // PKRF: three columns + official sublabels (old layout)
            return '<div class="pf-magallanes-address" data-magallanes-address>'
                . '<table class="pf-table" style="margin:0;"><tr>'
                . '<td style="width:33%;border:none;padding:0 4px 0 0;">' . $barangaySelect . '</td>'
                . '<td style="width:33%;border:none;padding:0 4px;">' . $municipality . '</td>'
                . '<td style="width:34%;border:none;padding:0 0 0 4px;">' . $province . '</td>'
                . '</tr><tr>'
                . '<td style="border:none;"><span class="pf-sublabel">(BARANGAY/TOWN)</span></td>'
                . '<td style="border:none;"><span class="pf-sublabel">(MUNICIPALITY/CITY)</span></td>'
                . '<td style="border:none;"><span class="pf-sublabel">(PROVINCE)</span></td>'
                . '</tr></table>'
                . '<div style="display:none;">' . $composed . '</div>'
                . '</div>';
        }

        // Enrollment: textarea then barangay / municipality / province rows (old layout)
        return '<div class="pf-magallanes-address" data-magallanes-address>'
            . $composed
            . '<table class="pf-table" style="margin-top:4px;border:none;"><tr>'
            . '<td style="border:none;padding:0 2px 0 0;">' . $barangaySelect . '</td>'
            . '<td style="border:none;padding:0 2px;">' . $municipality . '</td>'
            . '<td style="border:none;padding:0 0 0 2px;">' . $province . '</td>'
            . '</tr></table>'
            . '</div>';
    }

    public static function serialBoxes(string $name, int $count, string $role, string $group, bool $lockRecords): string
    {
        $state = self::resolveFieldState($role, $group, $lockRecords, ['name' => $name]);
        $html = '<div class="pf-serial-boxes">';
        for ($i = 0; $i < $count; $i++) {
            $html .= '<input type="text" maxlength="1" class="pf-box" name="' . self::name($name) . '[]" '
                . self::fg($group, $role, $state['editable'], $state['reason']) . ' ' . $state['attrs'] . '>';
        }
        return $html . '</div>';
    }

    public static function sectionBar(string $title): string
    {
        return '<div class="pf-section-bar">' . htmlspecialchars($title) . '</div>';
    }

    public static function formFooter(string $text): string
    {
        return '<div class="pf-form-footer">' . htmlspecialchars($text) . '</div>';
    }
}
