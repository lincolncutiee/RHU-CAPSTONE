<?php
/**
 * Paper-form rendering helpers — official DOH/PhilHealth layout.
 *
 * Editability is determined ONLY by Permissions + workflow lock.
 * Role instructional placeholders (e.g. "For Records Staff Only") are never shown.
 */

require_once __DIR__ . '/Permissions.php';
require_once __DIR__ . '/FormTemplate.php';

class PaperFormRenderer
{
    private static bool $layoutTestMode = false;
    private static bool $newConsultationMode = false;
    private static string $currentPageId = '';

    /** @var array<string, array<string, bool>>|null */
    private static ?array $requiredByPage = null;

    /** @var array<string, bool> */
    private static array $loggedFieldKeys = [];

    /** Phrases from the paper form that must not appear as digital placeholders. */
    private const ROLE_INSTRUCTION_PATTERNS = [
        '/^for\s+.+\s+only$/i',
        '/for records staff only/i',
        '/for nurse\s*\/?\s*midwife only/i',
        '/for attending physician only/i',
        '/for doctor only/i',
        '/for (the\s+)?(rhu|chu)(\s*\/\s*rhu)?\s+personnel only/i',
        '/for philhealth personnel only/i',
        '/for it department only/i',
        '/for receptionist only/i',
    ];

    private const AUTO_GENERATED_FIELDS = [
        'patient_id',
        'ekas_transaction_no',
        'ekas_date_generated',
    ];

    public static function setLayoutTestMode(bool $enabled): void
    {
        self::$layoutTestMode = $enabled;
    }

    public static function isLayoutTestMode(): bool
    {
        return self::$layoutTestMode;
    }

    public static function setNewConsultationMode(bool $enabled): void
    {
        self::$newConsultationMode = $enabled;
    }

    public static function isNewConsultationMode(): bool
    {
        return self::$newConsultationMode;
    }

    /**
     * Digital UI placeholders. Role labels are stripped — ownership is via data-field-group.
     */
    public static function placeholderForGroup(string $group, ?string $override = null, bool $autoGenerated = false): string
    {
        if (self::$layoutTestMode) {
            return '';
        }

        // Auto-generated fields stay blank; value comes from the system.
        if ($autoGenerated) {
            return '';
        }

        if ($override === null) {
            return '';
        }

        $override = trim($override);
        if ($override === '' || self::isRoleInstructionText($override)) {
            return '';
        }

        return $override;
    }

    public static function isRoleInstructionText(string $text): bool
    {
        $text = trim($text);
        if ($text === '') {
            return false;
        }

        foreach (self::ROLE_INSTRUCTION_PATTERNS as $pattern) {
            if (preg_match($pattern, $text)) {
                return true;
            }
        }

        return false;
    }

    public static function isAutoGeneratedField(string $name): bool
    {
        return in_array($name, self::AUTO_GENERATED_FIELDS, true);
    }

    private static function phAttr(string $text): string
    {
        if ($text === '' || self::isRoleInstructionText($text)) {
            return '';
        }
        $escaped = htmlspecialchars($text);
        return ' placeholder="' . $escaped . '"';
    }

    private static function profileAttr(string $name, bool $extended): string
    {
        require_once __DIR__ . '/PatientProfile.php';
        if ($extended && PatientProfile::isProfileExtended($name)) {
            $ro = self::$newConsultationMode ? ' data-profile-readonly="1" readonly' : '';
            return ' data-profile-field="' . htmlspecialchars($name) . '" data-profile-extended="1"' . $ro;
        }
        if (!$extended && PatientProfile::isProfileColumn($name)) {
            $ro = ($name === 'patient_id' || self::$newConsultationMode) ? ' data-profile-readonly="1" readonly' : '';
            return ' data-profile-field="' . htmlspecialchars($name) . '" data-profile-extended="0"' . $ro;
        }
        return '';
    }

    public static function isGroupReadonly(string $role, string $group, bool $lockRecords = false): bool
    {
        $role = Permissions::normalizeRole($role);
        $group = Permissions::normalizeGroup($group);

        // Workflow lock only applies to records-owned groups after submit / hard lock
        if ($lockRecords && in_array($group, ['records_enrollment', 'records_consent', 'records_treatment', 'it'], true)) {
            return true;
        }
        return Permissions::isReadonly($role, $group);
    }

    public static function renderPage(string $pageId, string $role, bool $lockRecords = false): string
    {
        $role = Permissions::normalizeRole($role);
        self::$currentPageId = $pageId;
        $path = __DIR__ . '/../forms/paper/' . $pageId . '.php';
        if (!file_exists($path)) {
            return '<div class="paper-sheet"><p class="text-danger">Form layout not found.</p></div>';
        }

        Permissions::debugLog(sprintf(
            'renderPage page=%s role=%s lockRecords=%s editableGroups=%s',
            $pageId,
            $role,
            $lockRecords ? '1' : '0',
            implode(',', Permissions::getEditableGroups($role))
        ));

        ob_start();
        include $path;
        $html = ob_get_clean();
        if (FormTemplate::isInlineEdit()) {
            $html = FormTemplate::augmentInlineEditableHtml($html, $pageId);
        } else {
            $html = FormTemplate::applyStaticTemplateCopy($html, $pageId);
        }
        self::$currentPageId = '';

        return $html;
    }

    /** Small caption under fields (admin-editable). */
    public static function sublabel(string $key, string $default): string
    {
        return '<span class="pf-sublabel">' . self::text($key, $default) . '</span>';
    }

    /** @return array<string, array<string, bool>> */
    private static function requiredByPage(): array
    {
        if (self::$requiredByPage !== null) {
            return self::$requiredByPage;
        }

        $rules = require __DIR__ . '/../config/form-completeness.php';
        $pageRules = [
            'pcsf'       => ['pcsf'],
            'itr'        => ['itr'],
            'enrollment' => ['enrollment'],
            'history'    => ['past_medical_history', 'past_surgical_history', 'family_history'],
            'personal'   => ['personal_social_history', 'ncd_assessment', 'photo_consent'],
            'ekas'       => ['ekas'],
            'epress'     => ['epress'],
        ];

        $map = [];
        foreach ($pageRules as $pageId => $keys) {
            $fields = [];
            foreach ($keys as $key) {
                $rule = $rules[$key] ?? [];
                foreach (['patient', 'treatment', 'extended', 'patient_consent'] as $bucket) {
                    foreach ($rule[$bucket] ?? [] as $field) {
                        $fields[(string) $field] = true;
                    }
                }
            }
            $map[$pageId] = $fields;
        }

        self::$requiredByPage = $map;
        return $map;
    }

    public static function isFieldRequired(string $fieldName, bool $extended = false): bool
    {
        return false;
    }

    /**
     * Paper form label with required (*) or optional hint.
     *
     * @param string      $text      Label text (plain; use labelHtml for markup)
     * @param string|null $fieldName Field name for requirement lookup
     * @param bool|null   $required  Force required/optional; null = auto from config
     */
    public static function label(string $text, ?string $fieldName = null, ?bool $required = null): string
    {
        $pageId = self::$currentPageId !== '' ? self::$currentPageId : null;
        $text = FormTemplate::fieldLabel($text, $fieldName, $pageId);
        $suffix = self::labelSuffix($fieldName, $required);
        $inner = htmlspecialchars($text, ENT_QUOTES, 'UTF-8') . $suffix;
        if (FormTemplate::isInlineEdit() && $fieldName !== null && $pageId !== null) {
            $key = FormTemplate::fieldLabelKey($pageId, $fieldName);
            $inner = FormTemplate::wrapInlineEditable($key, htmlspecialchars($text, ENT_QUOTES, 'UTF-8')) . $suffix;
        }
        return '<span class="pf-label">' . $inner . '</span>';
    }

    /** Label allowing safe inline HTML (e.g. &lt;br&gt;) in $html. */
    public static function labelHtml(string $html, ?string $fieldName = null, ?bool $required = null, string $extraClass = '', string $extraStyle = ''): string
    {
        $class = trim('pf-label ' . $extraClass);
        $style = $extraStyle !== '' ? ' style="' . htmlspecialchars($extraStyle) . '"' : '';
        $suffix = self::labelSuffix($fieldName, $required);
        $pageId = self::$currentPageId !== '' ? self::$currentPageId : null;
        $inner = $html;
        if ($fieldName !== null && $pageId !== null) {
            $key = FormTemplate::fieldLabelKey($pageId, $fieldName);
            $plainDefault = trim(strip_tags(str_replace(['<br>', '<br/>', '<br />'], "\n", $html)));
            $text = FormTemplate::get($key, $plainDefault);
            if (FormTemplate::isInlineEdit()) {
                $inner = FormTemplate::wrapInlineEditable($key, htmlspecialchars($text, ENT_QUOTES, 'UTF-8'));
            } else {
                $inner = nl2br(htmlspecialchars($text, ENT_QUOTES, 'UTF-8'));
            }
        }
        return '<span class="' . htmlspecialchars($class) . '"' . $style . '>' . $inner . $suffix . '</span>';
    }

    /** Admin-editable static line (plain text). */
    public static function text(string $key, string $default): string
    {
        $value = FormTemplate::get($key, $default);
        if (FormTemplate::isInlineEdit()) {
            return FormTemplate::wrapInlineEditable($key, htmlspecialchars($value, ENT_QUOTES, 'UTF-8'));
        }
        return htmlspecialchars($value, ENT_QUOTES, 'UTF-8');
    }

